"""Generate OpenAPI and complete Markdown API reference from routes and scenarios."""
import inspect
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit,parse_qs
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from security_backend.app import create_app
from security_backend.core import PREFIX,SERVICES,Settings
from scripts.scenarios import scenarios

ENUMS={'role':['Security Administrator','Security Analyst','Regular Employee/User','Auditor'],'severity':['Low','Medium','High','Critical'],'criticality':['Low','Medium','High','Critical'],'asset_type':['Server','Workstation','Database','Application','Network Device','Cloud Resource'],'account_status':['Active','Inactive','Suspended'],'threat_type':['IP Address','Domain','File Hash','Malware Signature','Other Indicators'],'notification_type':['Incident Assignment','Security Alert','System Notification','Threat Alert','Vulnerability Alert']}
DESCRIPTIONS={
 'full_name':'Full display name, 1 to 200 characters.','username':'Unique case-insensitive login, 3 to 40 characters, starts with a letter.','email':'Unique case-insensitive email.','password':'12 to 128 characters with uppercase, lowercase, digit and symbol.','login':'Username or email.','asset_id':'Existing affected asset ID. Incident reports may use null when the asset is unknown.','owner_id':'Existing active user ID.','analyst_id':'Existing active Security Analyst ID.','reporter_id':'Optional; if supplied, must equal the authenticated user ID.','cvss':'Number from 0 through 10.','cve':'CVE-YYYY-NNNN or longer numeric suffix; format is validated, external CVE existence is not.','resolution_date':'Timezone-aware ISO timestamp, not future or before record creation; requires resolved or closed status.','assigned_user_id':'Active analyst or administrator; analysts may claim/update only their own actions.','step_number':'Positive integer; must be the next consecutive response step.','content':'Investigation note up to 4000 characters.','status':'Validated lifecycle or resource status; see workflow documentation.','value':'Indicator value; type-specific IP, domain or hexadecimal hash validation.','read_date':'Server timestamp recorded on first read.','created_at':'UTC ISO timestamp generated by the server.'}

def schema_for(field,value):
    typ='integer' if field.endswith('_id') or field=='step_number' else 'number' if field=='cvss' else 'string'
    result={'type':typ,'description':DESCRIPTIONS.get(field,field.replace('_',' ').capitalize()+'.')}
    if field in ENUMS:result['enum']=ENUMS[field]
    if field=='cvss':result.update(minimum=0,maximum=10)
    if typ=='integer':result['minimum']=1
    if field=='password':result.update(minLength=12,maxLength=128,writeOnly=True)
    return result

def main():
    source=scenarios()
    records=json.loads((ROOT/'evidence/http-results.json').read_text(encoding='utf-8'))
    endpoints=[]
    spec={'openapi':'3.0.3','info':{'title':'Security Incident Detection and Response Backend','version':'1.0.0','description':'Abdulrahman Kobeissi. Nine independent local Flask services. All paths include the responsible student name.'},'components':{'securitySchemes':{'BearerAuth':{'type':'http','scheme':'bearer'}}},'paths':{}}
    for service,port in SERVICES.items():
        app=create_app(service,Settings('unused.db','x'*40))
        adapter=app.url_map.bind('localhost')
        mapped={}
        for scenario,record in zip(source,records):
            if scenario.service!=service:continue
            try:
                endpoint,args=adapter.match(urlsplit(record['url']).path,method=scenario.method)
            except Exception:continue
            mapped.setdefault((endpoint,scenario.method),[]).append((scenario,record))
        for rule in app.url_map.iter_rules():
            if '/internal/' in rule.rule or rule.rule.endswith(('/health','/openapi.json')):continue
            for method in sorted(rule.methods-{'HEAD','OPTIONS'}):
                variations=('summary','incidents','assets','threats','vulnerabilities','activity') if '<report_type>' in rule.rule else (None,)
                for variation in variations:
                    path=re.sub(r'<(?:int:)?(\w+)>',r'{\1}',rule.rule)
                    if variation:path=path.replace('{report_type}',variation)
                    candidates=mapped.get((rule.endpoint,method),[])
                    if variation:candidates=[x for x in candidates if x[0].path=='/reports/'+variation]
                    successes=[x for x in candidates if x[1]['response_status']<400]
                    first=(successes or candidates or [(None,None)])[0]
                    example_s,example_r=first
                    view=app.view_functions[rule.endpoint]
                    roles=inspect.getclosurevars(view).nonlocals.get('roles',())
                    purpose=example_s.name if example_s else rule.endpoint.replace('_',' ').capitalize()
                    if method=='POST' and path.endswith('/users/register'):purpose='Register an account'
                    op={'tags':[service],'summary':purpose,'operationId':service+'_'+rule.endpoint+'_'+method.lower()+(('_'+variation) if variation else ''),'description':'Owner: Abdulrahman Kobeissi. '+('Allowed roles: '+', '.join(roles)+'.' if roles else 'Public registration is restricted to active employees; login verifies credentials.'),'servers':[{'url':f'http://127.0.0.1:{port}'}],'responses':{},'parameters':[]}
                    if roles:op['security']=[{'BearerAuth':[]}]
                    for param in re.findall(r'\{(\w+)\}',path):op['parameters'].append({'name':param,'in':'path','required':True,'schema':{'type':'string' if param=='username' else 'integer'},'description':'Username to retrieve' if param=='username' else 'Positive record identifier'})
                    query={}
                    for sc,rec in candidates:query.update(parse_qs(urlsplit(sc.path).query))
                    for field in query:op['parameters'].append({'name':field,'in':'query','required':False,'schema':schema_for(field,None)})
                    body_fields={}
                    for sc,rec in successes:
                        if sc.body:body_fields.update(sc.body)
                    if body_fields:
                        required=list(body_fields) if method=='POST' else (['status'] if path.endswith('/status') or service=='playbooks' else ['role'] if path.endswith('/role') else ['analyst_id'] if path.endswith('/assign') else [])
                        required=[f for f in required if f not in ('reporter_id','account_status')]
                        optional={'assets':['operating_system','location','status'],'playbooks':['assigned_user_id']}
                        required=[f for f in required if f not in optional.get(service,[])]
                        body_schema={'type':'object','additionalProperties':False,'properties':{k:schema_for(k,v) for k,v in body_fields.items()}}
                        if required:body_schema['required']=required
                        if method=='PUT':body_schema['minProperties']=1
                        op['requestBody']={'required':True,'content':{'application/json':{'schema':body_schema,'example':example_r['request_body']}}}
                    codes={200:'Successful read or update',201:'Record created',400:'Invalid input',401:'Missing, invalid, expired or revoked token',403:'Role or ownership denied',404:'Record not found',409:'Uniqueness, relationship or workflow conflict',415:'JSON Content-Type required',429:'Login rate limit',503:'Required service unavailable'}
                    success_code=example_r['response_status'] if example_r else 200
                    used={success_code,400,401,403,404,409,503}
                    if method in ('POST','PUT'):used.add(415)
                    if path.endswith('/login'):used.add(429)
                    for code in sorted(used):
                        response={'description':codes.get(code,'Response')}
                        sample=next((rec['response_body'] for sc,rec in candidates if rec['response_status']==code),None)
                        if sample:response['content']={'application/json':{'example':sample}}
                        op['responses'][str(code)]=response
                    spec['paths'].setdefault(path,{})[method.lower()]=op
                    endpoints.append({'service':service,'port':port,'method':method,'path':path,'purpose':purpose,'roles':list(roles),'operation':op})
    (ROOT/'docs/openapi.json').write_text(json.dumps(spec,indent=2),encoding='utf-8')
    (ROOT/'docs/endpoint-catalog.json').write_text(json.dumps(endpoints,indent=2),encoding='utf-8')
    lines=['# API reference','', 'Responsible student: Abdulrahman Kobeissi.','', 'All examples below come from the live HTTP verification. Passwords and tokens are redacted. Request and response fields are JSON; protected calls require `Authorization: Bearer <token>`. List endpoints return arrays, single-resource endpoints return objects, both wrapped in `{ "status": "success", "data": ... }`. Error envelopes include `status`, `message` and `request_id`.','']
    for e in endpoints:
        op=e['operation']
        lines += [f'## {e["method"]} {e["path"]}', '',e['purpose']+'.', '',f'Service: {e["service"]}; base URL: http://127.0.0.1:{e["port"]}.', '',op['description'],'']
        if op['parameters']:
            lines+=['| Parameter | Location | Required | Description |','| --- | --- | --- | --- |']
            for p in op['parameters']:lines.append(f'| {p["name"]} | {p["in"]} | {p["required"]} | {p.get("description",p["schema"].get("description",""))} |')
            lines+=['']
        if 'requestBody' in op:
            body=op['requestBody']['content']['application/json']
            lines+=['Request fields: '+', '.join(body['schema']['properties'])+'.','Required fields: '+(', '.join(body['schema'].get('required',[])) or 'at least one permitted update field')+'.','','```json',json.dumps(body['example'],indent=2),'```','']
        for code,response in op['responses'].items():
            lines += [f'HTTP {code}: {response["description"]}.','']
            if 'content' in response and int(code)<400:
                lines+=['```json',json.dumps(response['content']['application/json']['example'],indent=2),'```','']
    (ROOT/'docs/API_REFERENCE.md').write_text('\n'.join(lines),encoding='utf-8')
    print(f'Documented {len(endpoints)} business API operations across {len(SERVICES)} services')

if __name__=='__main__':main()
